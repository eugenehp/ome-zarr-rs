def gen(shape, dtype, mod=251, offset=0):
    """Deterministic test data: ((i * 2654435761) % mod) - offset, cast."""
    n = int(np.prod(shape))
    v = (np.arange(n, dtype=np.uint64) * np.uint64(2654435761)) % np.uint64(mod)
    v = v.astype(np.int64) - offset
    if np.dtype(dtype).kind == "f":
        return (v.astype(np.float64) / 7.0).astype(dtype).reshape(shape)
    if np.dtype(dtype).kind == "b":
        return (v % 2 == 1).reshape(shape)
    return v.astype(dtype).reshape(shape)


def store(name):
    return str(STORES / name)


def jsonable(x):
    if isinstance(x, dict):
        return {str(k): jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [jsonable(v) for v in x]
    if isinstance(x, np.generic):
        return x.item()
    if isinstance(x, np.ndarray):
        return x.tolist()
    return x


def err(fn):
    try:
        fn()
    except Exception as e:  # noqa: BLE001
        return {"type": type(e).__name__, "msg": str(e)}
    return None


