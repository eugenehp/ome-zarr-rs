class Capture(logging.Handler):
    def __init__(self):
        super().__init__(logging.DEBUG)
        self.records = []

    def emit(self, r):
        if r.name.startswith("ome_zarr"):
            self.records.append([r.levelname, r.name, r.getMessage()])


def run_logged(fn, level):
    cap = Capture()
    root = logging.getLogger()
    old = root.level
    root.addHandler(cap)
    root.setLevel(level)
    out = io.StringIO()
    try:
        with contextlib.redirect_stdout(out):
            fn()
    finally:
        root.removeHandler(cap)
        root.setLevel(old)
    return {"stdout": out.getvalue(), "logs": cap.records}


